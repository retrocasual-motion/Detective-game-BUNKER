/**
 * Совмещение на стене (этап 4b-2b, решения автора 10.11 — WL-A, MG-A, SRC-A, JN-A).
 *
 * Обрывок, лежавший внутри материала (обгоревшая половина листа — п. 1 описи вещей Н. Харта,
 * файл 42), вынимают из листа — и он висит на стене своей карточкой «S:42/1». Две половины
 * одного листа, сведённые на стене рваными краями, складываются в одну карточку: движок
 * («ОСМОТР | 51 и 42 | совместить») отдаёт совмещённый лист, он висит вместо половин.
 * Канон не меняется: обрывок остаётся частью пакета 42, половины — в деле.
 */

export interface Piece {
  /** «42/1»: материал и номер предмета в нём. */
  key: string;
  /** Материал, внутри которого лежит обрывок. */
  from: string;
  /** Заголовок раздела материала, где он описан. */
  section: string;
  title: string;
}

export const PIECES: readonly Piece[] = [
  {
    key: '42/1',
    from: '42',
    section: 'Лист (п. 1)',
    title: 'Половина листа, обгоревшая (из личных вещей Н. Харта, п. 1)',
  },
];

/** Обрывок на стене: «S:42/1». */
export const pieceItemId = (key: string) => `S:${key}`;
export const pieceOf = (id: string) => PIECES.find((p) => pieceItemId(p.key) === id) ?? null;

/** Совмещение: какие две вещи стены (верх и низ) складываются в какой материал и чем. */
export interface Join {
  /** Совмещённый лист (выдаёт движок). */
  result: string;
  /** Верхняя половина — рваный край снизу. */
  top: string;
  /** Нижняя половина — рваный край сверху. */
  bottom: string;
  /** Запрос движку: «ОСМОТР | target | value». */
  target: string;
  value: string;
}

export const JOINS: readonly Join[] = [
  {
    result: 'L990',
    top: '51',
    bottom: pieceItemId('42/1'),
    target: '51 и 42',
    value: 'совместить',
  },
];

/** Где лежит нижняя половина, когда она сложена с верхней: смещение от верхней (мировые px). */
export const JOIN_OFFSET = { x: 0, y: 104 };
/** Насколько можно промахнуться, сводя края, — мировые px. */
export const JOIN_SNAP = 34;

/** Вещи стены, ушедшие в совмещённые листы: на стене их нет, висит совмещённый. */
export const joinedParts = (joined: readonly string[] = []) =>
  new Set(JOINS.filter((j) => joined.includes(j.result)).flatMap((j) => [j.top, j.bottom]));
