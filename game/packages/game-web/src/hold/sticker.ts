/**
 * Наклейка инвентарного номера на дне ноутбука Адама (A-283, ART-58, L947). Игрок сам берёт
 * ноутбук, сам переворачивает дном и сам приближает колесом — обычными жестами вещи в руках (Z-A,
 * автор 25.11: «как абсолютно все вещи, игрок сам смотрит и сам замечает»). Когда наклейка лицом к
 * камере и крупно — её крупный план (L947) ложится в дело; кнопок и подсказок нет.
 */

/** Ширина ноутбука класса E6400 ≈ 35 см — 2,8 единицы корпуса в `Laptop` (shapes.tsx). */
const UNITS_PER_CM = 2.8 / 35;
/** Наклейка 1492 × 1142 px ≈ 6 × 4,6 см; плоскость текстуры с полями грязи — 1652 × 1302 px. */
const PX_PER_CM = 1492 / 6;

/** Плоскость текстуры в единицах корпуса (ширина, высота). */
export const STICKER_SIZE: [number, number] = [
  (1652 / PX_PER_CM) * UNITS_PER_CM,
  (1302 / PX_PER_CM) * UNITS_PER_CM,
];

/**
 * Где на дне (единицы корпуса, как у коробки дна в `Laptop`): левая половина, ближе к переднему
 * краю — передний край дна z = 1,5; ножек у модели нет. Чуть ниже дна (y = −0,8): без мерцания.
 */
export const STICKER_AT: [number, number, number] = [-0.75, -0.8025, 1.1];

/** Действие движка: правило `zoom-laptop` (gm/access.json v3.4) принимает эту цель. */
export const STICKER_TARGET = '47 наклейка на дне ноутбука';

/**
 * Наклейка лицом к камере (косинус угла между её лицом и взглядом). Наклон вещи в руках — не больше
 * 80° (orient.ts), и корпус наклонён на 16°: дном к игроку ноутбук встаёт под углом около 26°
 * (косинус 0,9), порог — с запасом.
 */
export const FACING_MIN = 0.75;
/** Крупно: шире трети свободной части экрана (между папкой запроса и блокнотом). */
export const WIDTH_SHARE = 1 / 3;

/**
 * Достаточно ли близко рассмотрели: наклейка лицом к камере и на экране не уже трети свободной
 * области. corners — углы плоскости на экране, px.
 */
export function stickerSeen(
  corners: readonly { x: number; y: number }[],
  facing: number,
  freeWidth: number,
): boolean {
  if (facing < FACING_MIN || corners.length < 2 || freeWidth <= 0) return false;
  const xs = corners.map((c) => c.x);
  return Math.max(...xs) - Math.min(...xs) >= freeWidth * WIDTH_SHARE;
}
