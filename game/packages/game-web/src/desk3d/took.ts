/**
 * Чьё нажатие: 3D-стола или кнопки вещи следователя (DeskHotspots). Кнопка — прямоугольник по
 * контуру нарисованной вещи на экране; лист или устройство, лежащее перед ней (ближе к глазу),
 * накрыто этим прямоугольником. Нажатие сначала проверяет 3D-стол: ближе всех лист или устройство —
 * его берут, кнопка это нажатие пропускает; ближе нарисованная вещь (её невидимый объём,
 * `Occluders`) — нажатие её кнопке, как раньше.
 */
let seq = 0;
let took = -1;

if (typeof window !== 'undefined')
  window.addEventListener(
    'pointerdown',
    () => {
      seq += 1;
    },
    { capture: true },
  );

/** 3D-стол взял это нажатие (лист или устройство под мышью ближе нарисованной вещи). */
export function markDeskTook(): void {
  took = seq;
}

/** Это нажатие уже взял 3D-стол — кнопке вещи его не обрабатывать. */
export const deskTookPress = (): boolean => took === seq;
